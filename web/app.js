/* ---- one product, three-quarter view ----------------------------------- */
const ART_CACHE = new Map();
function art(r, opt) {
  opt = opt || {};
  const key = r.uid + "|" + (opt.max || 0) + "|" + (opt.scale || 0) + "|" + (opt.reflect ? 1 : 0);
  const hit = ART_CACHE.get(key);
  if (hit) return hit;

  const box = opt.max || 150, ghost = !r.d;
  const d = r.d || (r.shape === "cyl" ? {shape: "cyl", d: 21, h: 70}
                    : {shape: "box", w: 148, h: 200, t: 52});
  const assembled = r.kind === "module" || r.kind === "pack" || r.kind === "system";
  const dep = d.shape === "box" ? d.t * 0.3 : 0;          /* cabinet projection */
  const wmm = (d.shape === "cyl" ? d.d : d.w) + dep, hmm = d.h + dep;
  const scale = opt.scale || Math.min(box / wmm, box / hmm);
  const W = wmm * scale, H = hmm * scale, pad = 7, floor = 9;
  const refl = opt.reflect ? H * .42 : 0;
  const s = [];

  const EDGE = 'stroke="var(--metal-edge)" stroke-width=".8" stroke-linejoin="round"';
  const OUT = 'fill="none" stroke="var(--metal-edge)" stroke-width="1.2" stroke-dasharray="5 4" stroke-linejoin="round" opacity=".85"';
  const face = ghost ? OUT : `fill="url(#mF)" ${EDGE}`;

  if (!ghost) s.push(`<ellipse cx="${pad + W / 2}" cy="${pad + H + floor - 3}" rx="${W * .44}" ry="4.5" fill="url(#mSh)"/>`);

  if (d.shape === "cyl") {
    const w = d.d * scale, h = d.h * scale, x = pad + (W - w) / 2, y = pad;
    const ry = Math.min(w * .16, h * .34), nub = Math.max(w * .34, 3.5);
    s.push(`<path d="M${x} ${y + ry} v${h - ry * 2} a${w / 2} ${ry} 0 0 0 ${w} 0 v${-(h - ry * 2)}" ${face}/>`);
    s.push(`<ellipse cx="${x + w / 2}" cy="${y + ry}" rx="${w / 2}" ry="${ry}" ${ghost ? OUT : `fill="url(#mT)" ${EDGE}`}/>`);
    if (!ghost) {
      s.push(`<ellipse cx="${x + w / 2}" cy="${y + ry}" rx="${w * .35}" ry="${ry * .6}" fill="var(--metal-2)" stroke="var(--metal-edge)" stroke-width=".5" opacity=".9"/>`);
      s.push(`<ellipse cx="${x + w / 2}" cy="${y + ry * .55}" rx="${nub / 2}" ry="${ry * .28}" fill="var(--metal-hi)" stroke="var(--metal-edge)" stroke-width=".5"/>`);
      s.push(`<rect x="${x + w / 2 - nub / 2}" y="${y + ry * .55}" width="${nub}" height="${ry * .45}" fill="var(--metal-1)"/>`);
      s.push(`<line x1="${x + w * .87}" y1="${y + ry * 1.5}" x2="${x + w * .87}" y2="${y + h - ry * .7}" stroke="var(--metal-edge)" stroke-width=".5" opacity=".3"/>`);
      s.push(`<path d="M${x} ${y + ry * 2.1} a${w / 2} ${ry} 0 0 0 ${w} 0" fill="none" stroke="var(--metal-edge)" stroke-width=".5" opacity=".35"/>`);
    }
  } else {
    const w = d.w * scale, h = d.h * scale, dz = dep * scale;
    const x = pad, y = pad + dz, rr = Math.min(w, h) * .035;
    s.push(`<path d="M${x} ${y} l${dz} ${-dz} h${w} l${-dz} ${dz} z" ${ghost ? OUT : `fill="url(#mT)" ${EDGE}`}/>`);
    s.push(`<path d="M${x + w} ${y} l${dz} ${-dz} v${h} l${-dz} ${dz} z" ${ghost ? OUT : `fill="url(#mS)" ${EDGE}`}/>`);
    s.push(`<rect x="${x}" y="${y}" width="${w}" height="${h}" rx="${rr}" ${face}/>`);
    if (!ghost) {
      s.push(`<rect x="${x + w * .035}" y="${y + h * .022}" width="${w * .93}" height="${h * .956}" rx="${rr}" fill="none" stroke="var(--metal-edge)" stroke-width=".5" opacity=".28"/>`);
      const tw = Math.max(w * .13, 3.2), rise = Math.max(h * .012, 1.6);
      [x + w * .2 - tw / 2, x + w * .8 - tw / 2].forEach(tx => {
        s.push(`<rect x="${tx}" y="${y - rise}" width="${tw}" height="${rise + 1}" fill="var(--metal-2)" stroke="var(--metal-edge)" stroke-width=".5"/>`);
        s.push(`<path d="M${tx} ${y - rise} l${dz * .55} ${-dz * .55} h${tw} l${-dz * .55} ${dz * .55} z" fill="var(--metal-hi)" stroke="var(--metal-edge)" stroke-width=".5"/>`);
      });
      if (assembled)
        for (let i = 1; i < 4; i++)
          s.push(`<line x1="${x + w * i / 4}" y1="${y + h * .1}" x2="${x + w * i / 4}" y2="${y + h * .9}" stroke="var(--metal-edge)" stroke-width=".5" opacity=".45"/>`);
    }
  }

  const gid = "b" + ART_CACHE.size;
  const body = `<g id="${gid}">${s.join("")}</g>`;
  const mask = refl && !ghost
    ? `<mask id="${gid}m"><rect x="0" y="${pad + H}" width="${W + pad * 2}" height="${refl}" fill="url(#reflFade)"/></mask>`
    : "";
  const mirror = refl && !ghost
    ? `<defs>${mask}<linearGradient id="reflFade" x1="0" y1="0" x2="0" y2="1">
         <stop offset="0" stop-color="#fff" stop-opacity=".42"/><stop offset="1" stop-color="#fff" stop-opacity="0"/>
       </linearGradient></defs>
       <use href="#${gid}" transform="translate(0 ${2 * (pad + H)}) scale(1 -1)" mask="url(#${gid}m)" opacity=".5"/>`
    : "";
  const h = H + pad * 2 + floor + refl;
  const label = ghost ? "no published dimensions" : d.label;
  const out = {svg: `<svg viewBox="0 0 ${W + pad * 2} ${h}" width="${Math.round(W + pad * 2)}" height="${Math.round(h)}" role="img" aria-label="${esc(r.name)}, ${esc(label)}">${body}${mirror}</svg>`,
               label: label, ghost: ghost};
  ART_CACHE.set(key, out);
  return out;
}

/* ============================================================
   The isometric landscape
   ------------------------------------------------------------
   Camera over the +x +y corner:
       sx = (x - y)·cos30        sy = (x + y)·sin30 - z
   ============================================================ */
const C30 = Math.cos(Math.PI / 6), S30 = 0.5;
const px = (x, y, z, s) => [(x - y) * C30 * s, ((x + y) * S30 - z) * s];

function isoBox(x, y, z, w, dp, h, s, f) {
  const p = (X, Y, Z) => px(X, Y, Z, s).join(" ");
  const poly = (pts, fill) => `<polygon points="${pts}" fill="${fill}" stroke="${f.edge}" stroke-width=".7" stroke-linejoin="round"/>`;
  return poly([p(x, y, z + h), p(x + w, y, z + h), p(x + w, y + dp, z + h), p(x, y + dp, z + h)].join(" "), f.top)
       + poly([p(x, y + dp, z), p(x + w, y + dp, z), p(x + w, y + dp, z + h), p(x, y + dp, z + h)].join(" "), f.left)
       + poly([p(x + w, y, z), p(x + w, y + dp, z), p(x + w, y + dp, z + h), p(x + w, y, z + h)].join(" "), f.right);
}

function isoCyl(x, y, z, r, h, s, f) {
  const rx = r * C30 * Math.SQRT2 * s, ry = r * S30 * Math.SQRT2 * s;
  const top = px(x, y, z + h, s), bot = px(x, y, z, s);
  return `<path d="M${top[0] - rx} ${top[1]} v${bot[1] - top[1]} a${rx} ${ry} 0 0 0 ${rx * 2} 0 v${top[1] - bot[1]} z"
            fill="${f.left}" stroke="${f.edge}" stroke-width=".7"/>
          <ellipse cx="${top[0]}" cy="${top[1]}" rx="${rx}" ry="${ry}" fill="${f.top}" stroke="${f.edge}" stroke-width=".7"/>
          <ellipse cx="${top[0]}" cy="${top[1]}" rx="${rx * .52}" ry="${ry * .52}" fill="${f.right}" stroke="${f.edge}" stroke-width=".5" opacity=".8"/>`;
}

const ISO_W = {top: "url(#iT)", left: "url(#iL)", right: "url(#iR)", edge: "var(--iso-edge)"};
const ISO_B = {top: "url(#bT)", left: "url(#bL)", right: "url(#bR)", edge: "var(--iso-blue-edge)"};

/* One product standing at (x, y) on the plane. */
function isoProduct(r, x, y, s) {
  const d = r.d;
  if (!d) return null;
  const assembled = r.kind === "module" || r.kind === "pack" || r.kind === "system";
  const F = assembled ? ISO_B : ISO_W;
  let body, w, dp, h;

  if (d.shape === "cyl") {
    w = dp = d.d; h = d.h;
    body = isoCyl(x + d.d / 2, y + d.d / 2, 0, d.d / 2, d.h, s, F);
  } else {
    w = d.w; dp = d.t; h = d.h;
    body = isoBox(x, y, 0, w, dp, h, s, F);
    const tw = w * .13, td = dp * .34, th = Math.max(h * .014, 2 / s);
    [w * .2, w * .8 - tw].forEach(o => {
      body += isoBox(x + o, y + dp * .33, h, tw, td, th, s,
                     {top: F.top, left: F.right, right: F.right, edge: F.edge});
    });
    if (assembled)
      for (let i = 1; i < 4; i++) {
        const a = px(x + w * i / 4, y + dp, 0, s), b = px(x + w * i / 4, y + dp, h, s);
        body += `<line x1="${a[0]}" y1="${a[1]}" x2="${b[0]}" y2="${b[1]}" stroke="var(--iso-edge)" stroke-width=".6" opacity=".5"/>`;
      }
  }
  const c = px(x + w / 2, y + dp / 2, 0, s);
  const shadow = `<ellipse cx="${c[0]}" cy="${c[1]}" rx="${(w + dp) * .42 * C30 * s}" ry="${(w + dp) * .40 * S30 * s}" fill="url(#iSh)"/>`;
  return {svg: shadow + body, pin: px(x + w / 2, y + dp / 2, h, s), depth: x + y, h: h,
          foot: px(x + w / 2, y + dp / 2, 0, s)};
}

/* The whole plane: a grid, the current running between the objects, and the
   objects themselves, each with a marker that opens its page. */
function landscape(list, opt) {
  opt = opt || {};
  const foot = r => r.d.shape === "cyl" ? r.d.d : Math.max(r.d.w, r.d.t);
  const cells = list.filter(r => r.d).slice(0, 7).sort((a, b) => b.d.h - a.d.h);
  if (!cells.length) return "";
  const pitch = Math.max(...cells.map(foot)) * 1.15;
  const GRID = [[0, 0], [1, 0], [0, 1], [2, 0], [1, 1], [0, 2], [2, 1], [1, 2], [2, 2]];

  const s = 1;
  /* one pass: position, draw and remember, rather than drawing twice */
  const drawn = cells.map((r, i) => {
    const g = GRID[i], d = r.d;
    const w = d.shape === "cyl" ? d.d : d.w, dp = d.shape === "cyl" ? d.d : d.t;
    const at = [g[0] * pitch + (pitch - w) / 2, g[1] * pitch + (pitch - dp) / 2];
    return {r: r, at: at, w: w, dp: dp, out: isoProduct(r, at[0], at[1], s)};
  });

  const m = pitch * .3;
  const O = {x: Math.min(...drawn.map(o => o.at[0])) - m, y: Math.min(...drawn.map(o => o.at[1])) - m};
  const PLOT = {w: Math.max(...drawn.map(o => o.at[0] + o.w)) + m - O.x,
                d: Math.max(...drawn.map(o => o.at[1] + o.dp)) + m - O.y};

  const pts = [];
  [[0, 0], [PLOT.w, 0], [PLOT.w, PLOT.d], [0, PLOT.d]]
    .forEach(c => pts.push(px(O.x + c[0], O.y + c[1], 0, s)));
  drawn.forEach(o => { pts.push(o.out.pin); pts.push([o.out.pin[0], o.out.pin[1] + 10]); });
  const xs = pts.map(p => p[0]), ys = pts.map(p => p[1]), pad = pitch * .1;
  const vb = {x: Math.min(...xs) - pad, y: Math.min(...ys) - pad * 1.4,
              w: Math.max(...xs) - Math.min(...xs) + pad * 2,
              h: Math.max(...ys) - Math.min(...ys) + pad * 2.2};
  const AR = opt.aspect || 2.45;
  if (vb.w / vb.h < AR) { const w = vb.h * AR; vb.x -= (w - vb.w) / 2; vb.w = w; }
  else { const h = vb.w / AR; vb.y -= (h - vb.h) / 2; vb.h = h; }

  const grid = [], step = pitch / 2;
  for (let gx = 0; gx <= PLOT.w; gx += step) {
    const a = px(O.x + gx, O.y, 0, s), b = px(O.x + gx, O.y + PLOT.d, 0, s);
    grid.push(`<line x1="${a[0]}" y1="${a[1]}" x2="${b[0]}" y2="${b[1]}"/>`);
  }
  for (let gy = 0; gy <= PLOT.d; gy += step) {
    const a = px(O.x, O.y + gy, 0, s), b = px(O.x + PLOT.w, O.y + gy, 0, s);
    grid.push(`<line x1="${a[0]}" y1="${a[1]}" x2="${b[0]}" y2="${b[1]}"/>`);
  }
  const plate = [[0, 0], [PLOT.w, 0], [PLOT.w, PLOT.d], [0, PLOT.d]]
    .map(c => px(O.x + c[0], O.y + c[1], 0, s).join(" ")).join(" ");
  const path = drawn.map((o, i) => (i ? "L" : "M") + o.out.foot[0] + " " + o.out.foot[1]).join(" ");

  const order = drawn.slice().sort((a, b) => a.out.depth - b.out.depth);
  const svg = `<svg class="land" viewBox="${vb.x} ${vb.y} ${vb.w} ${vb.h}" role="img"
      aria-label="An isometric drawing of ${plural(order.length, "product")} from the library, each at its published size">
    <polygon points="${plate}" fill="var(--iso-plate)"/>
    <g stroke="var(--iso-grid)" stroke-width=".9">${grid.join("")}</g>
    <path d="${path}" fill="none" stroke="var(--acc-2)" stroke-width="2.2" opacity=".5"
      stroke-linecap="round" stroke-dasharray="9 13" class="flow"/>
    ${order.map((o, i) => `<g class="obj" style="animation-delay:${180 + i * 110}ms">${o.out.svg}</g>`).join("")}
  </svg>`;

  const tallest = Math.max(...order.map(o => o.out.h));
  const placed = order.map(o => ({o: o, top: (o.out.pin[1] - vb.y) / vb.h * 100,
                                 left: (o.out.pin[0] - vb.x) / vb.w * 100}));
  const opener = placed.filter(q => q.top > 34).sort((a, b) => b.o.out.depth - a.o.out.depth)[0];
  const pins = placed.map((q, i) => `<a class="pin${q === opener ? " on" : ""}${q.top < 26 ? " below" : ""}"
      href="${q.o.r.href}" style="left:${q.left.toFixed(2)}%;top:${q.top.toFixed(2)}%;animation-delay:${420 + i * 110}ms">
      <span class="dot" aria-hidden="true"></span>
      <span class="tag"><b>${esc(q.o.r.model)}</b>${q.o.r.fact ? `<i>${esc(q.o.r.fact)}</i>` : ""}</span>
    </a>`).join("");
  return `<div class="land-wrap">${svg}${pins}</div>`;
}

/* ---- the product-family glyphs ----------------------------------------- */
function glyph(kind) {
  const W = ISO_W, B = ISO_B, solids = [];
  const box = (x, y, z, w, d, h, f) => solids.push([x, y, z, w, d, h, f]);
  let extra = "";

  if (kind === "design") {
    box(0, 0, 0, 62, 30, 84, W); box(80, 8, 0, 10, 10, 84, B); box(80, 8, 88, 10, 10, 6, B);
  } else if (kind === "core") {
    box(0, 0, 0, 78, 56, 9, W); box(0, 0, 16, 78, 56, 9, B);
    box(0, 0, 32, 78, 56, 9, W); box(0, 0, 48, 78, 56, 9, B);
  } else if (kind === "data") {
    for (let i = 0; i < 3; i++) for (let j = 0; j < 3; j++) box(i * 34, j * 34, 0, 26, 26, 9, W);
    box(34, 34, 22, 26, 26, 9, B);
  } else if (kind === "market") {
    [30, 52, 78, 112].forEach((h, i) => box(i * 26, 0, 0, 17, 30, h, i === 3 ? B : W));
  } else if (kind === "health") {
    box(0, 0, 0, 54, 30, 88, W);
    [66, 48, 32, 18].forEach((h, i) => box(70 + i * 19, 6, 0, 12, 18, h, B));
  } else if (kind === "cup") {
    box(0, 0, 0, 32, 32, 54, W); box(36, 0, 0, 32, 32, 84, B); box(72, 0, 0, 32, 32, 38, W);
  } else if (kind === "recycle") {
    const at = [[0, 0], [92, 12], [42, 88]];
    at.forEach((a, i) => box(a[0], a[1], 0, 30, 26, 40 + i * 8, i === 1 ? B : W));
    const p = at.map(a => px(a[0] + 15, a[1] + 13, 0, 1));
    extra = `<path d="M${p[0][0]} ${p[0][1]} L${p[1][0]} ${p[1][1]} L${p[2][0]} ${p[2][1]} Z"
      fill="none" stroke="var(--acc-2)" stroke-width="2.6" stroke-dasharray="8 10"
      stroke-linecap="round" class="flow" opacity=".8"/>`;
  }

  const pts = [];
  solids.forEach(b => {
    for (const X of [b[0], b[0] + b[3]]) for (const Y of [b[1], b[1] + b[4]])
      for (const Z of [b[2], b[2] + b[5]]) pts.push(px(X, Y, Z, 1));
  });
  const xs = pts.map(p => p[0]), ys = pts.map(p => p[1]), m = 8;
  const vb = [Math.min(...xs) - m, Math.min(...ys) - m,
              Math.max(...xs) - Math.min(...xs) + m * 2, Math.max(...ys) - Math.min(...ys) + m * 2];
  const body = solids.sort((a, b) => (a[0] + a[1] + a[2] * .01) - (b[0] + b[1] + b[2] * .01))
    .map(b => isoBox(b[0], b[1], b[2], b[3], b[4], b[5], 1, b[6])).join("");
  return `<svg class="glyph" viewBox="${vb.join(" ")}" role="presentation" aria-hidden="true">${extra}${body}</svg>`;
}

/* ============================================================
   The cell under load — Rust, compiled to WebAssembly
   ------------------------------------------------------------
   Only the product pages load sim.js, so nobody downloads a
   physics model to look at a list. The inputs are worked out
   in Python and printed into the page, so this end only has to
   turn a slider into a call and a call into a curve.
   ============================================================ */
const SIM = {ready: false};
function labBoot() {
  if (typeof WebAssembly !== "object" || !window.BD_SIM_WASM) return;
  try {
    const bin = Uint8Array.from(atob(window.BD_SIM_WASM), c => c.charCodeAt(0));
    WebAssembly.instantiate(bin, {}).then(w => {
      const e = w.instance.exports;
      SIM.fn = e.simulate; SIM.mem = e.memory; SIM.ptr = e.out_ptr(); SIM.n = e.points();
      SIM.ready = true;
      if (window.BD_LAB) labMount(window.BD_LAB);
    }).catch(() => {});
  } catch (e) { /* a browser without WebAssembly still gets the whole page */ }
}

function labPlot(pts, inp, hot) {
  const W = 560, H = 300, L = 46, R = 12, TOP = 14, B = 34;
  if (!pts.length) return `<svg viewBox="0 0 ${W} ${H}"></svg>`;
  const maxAh = Math.max(inp.cap, pts[pts.length - 1][0]) || 1;
  const lo = Math.min(inp.vmin - .05, ...pts.map(q => q[1]));
  const hi = Math.max(inp.vmax, ...pts.map(q => q[1]));
  const X = a => L + (a / maxAh) * (W - L - R);
  const Y = v => TOP + (1 - (v - lo) / (hi - lo)) * (H - TOP - B);
  const line = pts.map((q, i) => (i ? "L" : "M") + X(q[0]).toFixed(1) + " " + Y(q[1]).toFixed(1)).join(" ");
  const area = line + ` L${X(pts[pts.length - 1][0]).toFixed(1)} ${Y(lo)} L${X(0)} ${Y(lo)} Z`;
  const vt = [], stepV = (hi - lo) > 1.2 ? .5 : .25;
  for (let v = Math.ceil(lo / stepV) * stepV; v <= hi; v += stepV) vt.push(v);
  const at = [0, .25, .5, .75, 1].map(f => f * maxAh);

  return `<svg viewBox="0 0 ${W} ${H}" role="img"
      aria-label="Terminal voltage against charge delivered, ${num(pts[pts.length - 1][0])} amp-hours to the cut-off">
    ${vt.map(v => `<line x1="${L}" y1="${Y(v).toFixed(1)}" x2="${W - R}" y2="${Y(v).toFixed(1)}"
        stroke="var(--hair)" stroke-width="1"/>
      <text x="${L - 8}" y="${(Y(v) + 4).toFixed(1)}" text-anchor="end" font-size="10.5"
        fill="var(--ink-3)">${v.toFixed(2).replace(/0$/, "")}</text>`).join("")}
    ${at.map(a => `<text x="${X(a).toFixed(1)}" y="${H - 12}" text-anchor="middle" font-size="10.5"
        fill="var(--ink-3)">${num(a)}</text>`).join("")}
    <text x="${L - 8}" y="${TOP + 2}" text-anchor="end" font-size="10" fill="var(--ink-3)">V</text>
    <text x="${W - R}" y="${TOP + 2}" text-anchor="end" font-size="10" fill="var(--ink-3)">Ah delivered</text>
    <line x1="${L}" y1="${Y(inp.vmin).toFixed(1)}" x2="${W - R}" y2="${Y(inp.vmin).toFixed(1)}"
      stroke="var(--flag)" stroke-width="1.2" stroke-dasharray="5 5" opacity=".85"/>
    <text x="${L + 6}" y="${(Y(inp.vmin) - 6).toFixed(1)}" font-size="10.5"
      fill="var(--flag)">cut-off ${num(inp.vmin)} V</text>
    <path d="${area}" fill="url(#labFill)"/>
    <path d="${line}" fill="none" stroke="${hot ? "var(--flag)" : "var(--acc-1)"}" stroke-width="2.6"
      stroke-linejoin="round" stroke-linecap="round"/>
    <circle cx="${X(pts[pts.length - 1][0]).toFixed(1)}" cy="${Y(pts[pts.length - 1][1]).toFixed(1)}" r="4.5"
      fill="var(--bg)" stroke="${hot ? "var(--flag)" : "var(--acc-1)"}" stroke-width="2.4"/>
  </svg>`;
}

function labMount(inp) {
  const cS = document.getElementById("labC"), tS = document.getElementById("labT");
  if (!cS || !SIM.ready) return;
  const set = (id, v, u) => { document.getElementById(id).innerHTML = v + (u ? `<small>${u}</small>` : ""); };
  let queued = false;

  function draw() {
    queued = false;
    const c = +cS.value / 100, t = +tS.value;
    cS.style.setProperty("--pct", (cS.value - cS.min) / (cS.max - cS.min) * 100 + "%");
    tS.style.setProperty("--pct", (tS.value - tS.min) / (tS.max - tS.min) * 100 + "%");
    document.getElementById("labCV").textContent = c.toFixed(2).replace(/0$/, "") + " C";
    document.getElementById("labTV").textContent = t + " °C";

    const n = SIM.fn(inp.cap, inp.vmax, inp.vmin, inp.r, inp.mass, c, t, inp.flat ? 1 : 0);
    const f = new Float32Array(SIM.mem.buffer, SIM.ptr, SIM.n * 3 + 16);
    const pts = [];
    for (let i = 0; i < n; i++) pts.push([f[i] * inp.cap, f[SIM.n + i]]);
    const s = i => f[SIM.n * 3 + i];

    document.getElementById("labplot").innerHTML = labPlot(pts, inp, s(6) > 12);
    set("labAh", num(s(0)), "Ah");
    set("labWh", num(s(1)), "Wh");
    const secs = s(3);
    document.getElementById("labT2").textContent = secs >= 3600
      ? (secs / 3600).toFixed(1) + " h" : Math.round(secs / 60) + " min";
    set("labPct", Math.round(s(7) * 100), "%");
    set("labWhkg", inp.mass ? num(s(2)) : "—", inp.mass ? "Wh/kg" : "");
    set("labDT", inp.mass ? "+" + num(s(6)) : "—", inp.mass ? "K" : "");
    document.getElementById("labCA").textContent = num(s(8)) + " A out of a " + num(inp.cap) + " Ah cell";
    document.querySelectorAll("#labPre button").forEach(b =>
      b.setAttribute("aria-pressed", +b.dataset.c === +cS.value && +b.dataset.t === +tS.value));
  }
  /* one draw per frame however fast the slider is dragged */
  const run = () => { if (!queued) { queued = true; requestAnimationFrame(draw); } };

  cS.addEventListener("input", run);
  tS.addEventListener("input", run);
  document.getElementById("labPre").addEventListener("click", e => {
    const b = e.target.closest("button[data-c]");
    if (!b) return;
    cS.value = b.dataset.c; tS.value = b.dataset.t; draw();
  });
  draw();
}

