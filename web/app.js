/* ============================================================
   battery-data — the shared runtime
   ------------------------------------------------------------
   Every page loads this once and the browser caches it. It
   holds the drawing, the number formatting and the two
   interactive parts; the pages themselves are static HTML
   generated by tools/build_site.py, so nothing here has to
   render a page before a reader can read it.

   The one rule that shapes this file: a page only ever carries
   the data it shows. The library's 600 values live on the 64
   product pages, one page each, not in a blob every visitor
   downloads to look at the home page.
   ============================================================ */
"use strict";

/* ---- numbers ----------------------------------------------------------- */
function num(v) {
  if (v == null || v === "") return "";
  const n = Number(v);
  if (!isFinite(n)) return String(v);
  const abs = Math.abs(n);
  const dp = abs >= 1000 ? 0 : abs >= 100 ? 1 : abs >= 1 ? 2 : 4;
  return n.toLocaleString("en-US", {maximumFractionDigits: dp});
}
const esc = s => String(s == null ? "" : s)
  .replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;").replace(/"/g, "&quot;");
const plural = (n, one, many) => n + " " + (n === 1 ? one : (many || one + "s"));

